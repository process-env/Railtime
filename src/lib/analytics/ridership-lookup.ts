/** Pre-pandemic (2019) average weekday ridership */
export const PRE_PANDEMIC_DAILY_AVG = 5_500_000;

/** MTA single ride fare (2025 rate) */
export const SUBWAY_FARE = 3.00;

/** 2025 overall daily average */
export const AVG_DAILY_2025 = 3558779;

/** 2025 weekday average */
export const AVG_WEEKDAY_2025 = 4005650;

/**
 * Get ridership for a given date using last-year lookup.
 * Falls back to overall 2025 daily average if date not found.
 */
export function getRidershipForDate(date: Date = new Date()): {
  ridership: number;
  prePandemicPercent: number;
  dailyFareRevenue: number;
  date: string;
  isEstimate: boolean;
} {
  const mm = String(date.getMonth() + 1).padStart(2, '0');
  const dd = String(date.getDate()).padStart(2, '0');
  const key = mm + '-' + dd; // Use local time, not UTC (user's browser time)
  
  const ridership = RIDERSHIP_2025[key] ?? AVG_DAILY_2025;
  const isEstimate = !(key in RIDERSHIP_2025);
  const prePandemicPercent = Math.round((ridership / PRE_PANDEMIC_DAILY_AVG) * 1000) / 10;
  const dailyFareRevenue = Math.round(ridership * SUBWAY_FARE);
  
  return {
    ridership,
    prePandemicPercent,
    dailyFareRevenue,
    date: date.toISOString().split('T')[0],
    isEstimate,
  };
}

/**
 * Get ridership for a range of days (counting back from today).
 * Returns data in descending order (most recent first).
 */
export function getRidershipRange(days: number = 30): {
  ridership: number;
  prePandemicPercent: number;
  date: string;
}[] {
  const result = [];
  const now = new Date();
  for (let i = 0; i < days; i++) {
    const d = new Date(now);
    d.setDate(d.getDate() - i);
    const info = getRidershipForDate(d);
    result.push({
      ridership: info.ridership,
      prePandemicPercent: info.prePandemicPercent,
      date: info.date,
    });
  }
  return result;
}
